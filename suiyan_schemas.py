# -*- coding: utf-8 -*-
"""SuiYan AI - data contracts (schemas) for the beauty hackathon track 3.

This module defines the interface contract between the vision module
(skin profile detection) and the RAG module (makeup plan generation):

    SkinProfile  --JSON-->  RAG chain  --JSON-->  MakeupPlan

All models use pydantic so that LangChain's JsonOutputParser can enforce
the output structure on the LLM response.
"""
from typing import List, Optional

from pydantic import BaseModel, Field

# ---------------------------------------------------------------------------
# Input: skin profile JSON produced by the vision module
# ---------------------------------------------------------------------------
class SkinProfile(BaseModel):
    """Skin profile detected from a portrait photo (vision module output)."""
    skin_type: str = Field(
        description="肤质类型: 干性 / 油性 / 混合性 / 中性 / 敏感肌"
    )
    skin_tone: str = Field(
        description="肤色深浅档: 冷白 / 自然 / 小麦 / 暖黄二白 / 暖黄三白 等"
    )
    undertone: str = Field(
        description="底调: 冷调 / 暖调 / 中性调"
    )
    concerns: List[str] = Field(
        default_factory=list,
        description="肌肤关注点列表, 例如: 法令纹, 眼周细纹, 暗沉, 斑点, 毛孔",
    )
    occasion: str = Field(
        default="日常通勤",
        description="妆容场合: 日常通勤 / 宴会聚会 / 户外出游 / 重要活动",
    )
    user_request: Optional[str] = Field(
        default=None,
        description="用户语音需求原文（语音转写），例如: 我下周参加婚礼，想要显气色，预算300以内。优先级高于默认场合。",
    )


# ---------------------------------------------------------------------------
# Output: makeup plan JSON generated by the RAG chain
# ---------------------------------------------------------------------------
class ProductRef(BaseModel):
    """One recommended product inside a makeup plan.

    `name` MUST come from the retrieved candidate list (anti-hallucination),
    `shade` MUST be one of that product's shade_ids (or null for skincare).
    """
    name: str = Field(description="产品全名, 必须来自候选产品清单")
    category: Optional[str] = Field(
        default=None,
        description="产品类别(粉底/气垫/口红/唇釉/面霜/眼霜/精华/防晒/化妆水/面膜), 必须与候选清单中该产品的类别一致",
    )
    shade: Optional[str] = Field(
        default=None,
        description="选定色号ID, 必须是该产品shades中的色号; 护肤品留空",
    )
    reason: str = Field(description="推荐理由, 结合用户肤质/肤色/场合说明")
    usage_hint: str = Field(default="", description="该产品的使用要点提示")


class MakeupPlan(BaseModel):
    """Final structured output: positioning + products + big-font steps."""
    positioning: str = Field(
        description="妆容定位一句话, 例如: 温柔气色通勤妆 - 以原生气质为主, 只提气色不动纹路"
    )
    products: List[ProductRef] = Field(
        description="推荐产品清单, 4-7个, 必须全部来自候选清单"
    )
    steps: List[str] = Field(
        description="大字版化妆步骤, 按顺序7-10步, 每步一句话加要点, 面向熟龄肌"
    )
    native_note: str = Field(
        description="原生感提示: 说明哪些特征被保留/优化(如保留皱纹只提气色), 呼应赛题'不去皱纹'理念"
    )


# Parser instance reused by the chain
PLAN_PARSER_FORMAT = None  # filled lazily in chain module to avoid heavy import


def profile_to_text(profile: SkinProfile) -> str:
    """Flatten a SkinProfile into a compact Chinese text for retrieval queries."""
    return (
        f"{profile.skin_type}肌 {profile.skin_tone} {profile.undertone} "
        f"关注: {'、'.join(profile.concerns) if profile.concerns else '无特别'} "
        f"场合: {profile.occasion} 熟龄肌彩妆"
    )
